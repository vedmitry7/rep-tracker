def import_preview(*, exercises: str, entries: str, total_reps: str, date_from: str, date_to: str, new_count: str, existing_names: list[str]) -> str:
    value = f'📥 Impor\n\nLatihan: {exercises}\nEntri latihan: {entries}\nJumlah repetisi: {total_reps}\nRentang tanggal: {date_from} — {date_to}\n\nLatihan baru: {new_count}\nLatihan yang ada: {len(existing_names)}'
