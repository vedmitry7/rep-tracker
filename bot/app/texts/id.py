def import_confirmation(strategy: str, entries: str, existing_count: int) -> str:
    if strategy == 'replace':
        return f'Ganti riwayat yang ada?\n\nSejarah untuk {existing_count} latihan yang cocok akan dihapus secara permanen.\n{entries} entri yang diimpor kemudian akan ditambahkan.'
    return f'Gabungkan data yang diimpor?\n\nEntri yang ada akan tetap ada.\n{entries} entri baru akan ditambahkan.\n\nImpor berulang dapat menghasilkan duplikat.'

def import_completed(*, strategy: str, created: str, updated: str, entries: str, total_reps: str, include_strategy: bool=True) -> str:
    strategy_name = 'Ganti' if strategy == 'replace' else 'Gabungkan'
    value = '✅ Impor selesai\n\n'
    if include_strategy:
        value += f'Strategi: {strategy_name}\n\n'
    return value + f'Latihan yang dibuat: {created}\nLatihan yang ada diperbarui: {updated}\nEntri yang diimpor: {entries}\nTotal repetisi yang diimpor:{total_reps}'

