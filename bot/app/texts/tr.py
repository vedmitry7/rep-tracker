def import_confirmation(strategy: str, entries: str, existing_count: int) -> str:
    if strategy == 'replace':
        return f'Mevcut geçmiş değiştirilsin mi?\n\nGeçmişi {existing_count} eşleştirme alıştırmaları kalıcı olarak silinecektir.\n{entries} içe aktarılan girişler daha sonra eklenecektir.'
    return f'İçe aktarılan veriler birleştirilsin mi?\n\nMevcut girişler kalacaktır.\n{entries} yeni girişler eklenecektir.\n\nTekrarlanan içe aktarma kopyalar oluşturabilir.'

def import_completed(*, strategy: str, created: str, updated: str, entries: str, total_reps: str, include_strategy: bool=True) -> str:
    strategy_name = 'Değiştir' if strategy == 'replace' else 'Birleştir'
    value = '✅ İçe aktarma tamamlandı\n\n'
    if include_strategy:
        value += f'Strateji: {strategy_name}\n\n'
    return value + f'Oluşturulan egzersizler: {created}\nMevcut egzersizler güncellendi: {updated}\nİçe aktarılan girişler: {entries}\nİçe aktarılan toplam temsilci sayısı:{total_reps}'

